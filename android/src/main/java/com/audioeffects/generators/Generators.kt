package com.audioeffects.generators

import com.vectencia.klarinet.AudioStreamCallback
import java.util.concurrent.atomic.AtomicInteger
import kotlin.math.PI
import kotlin.math.abs
import kotlin.math.sin
import kotlin.random.Random

/**
 * Oscillators and noise sources.
 *
 * Klarinet 0.5 ships no generators, so these synthesise samples directly in
 * [AudioStreamCallback.onAudioReady]. That callback runs on a worker thread
 * rather than the real-time audio thread, so allocation here is safe — but
 * slow work still causes underruns, hence the plain float maths and the
 * preallocated state.
 *
 * ## Aliasing
 *
 * A naive saw or square is generated by sampling a discontinuous function,
 * which produces harmonics above Nyquist that fold back down into the
 * audible band as inharmonic tones — the characteristic cheap-digital whine
 * that gets worse as pitch rises.
 *
 * PolyBLEP (polynomial band-limited step) fixes this by rounding off each
 * discontinuity over a two-sample window, cancelling most of the energy that
 * would otherwise alias. It is far cheaper than a wavetable set and good
 * enough that the result is perceptually equivalent to AudioKit's band-limited
 * tables on iOS — though not sample-identical, which is why the schema
 * documents the difference.
 *
 * Triangle is generated naively on purpose: its harmonics fall off as 1/n²,
 * so what aliases is far enough down to be inaudible and the extra cost is
 * not worth paying.
 */

/**
 * ADSR amplitude envelope.
 *
 * Klarinet has no envelope of its own, but the generator owns its callback,
 * so the shape is applied per sample here. Attack and decay are linear ramps
 * and release is exponential, which is the usual pairing: a linear attack
 * sounds immediate, while a linear release sounds like it stops abruptly
 * rather than fading.
 *
 * Mirrors `AmplitudeEnvelope` on iOS, which takes the same four parameters.
 */
internal class Envelope(private val sampleRate: Int) {
  private enum class Stage { IDLE, ATTACK, DECAY, SUSTAIN, RELEASE }

  @Volatile var attackMs = 10f
  @Volatile var decayMs = 200f
  @Volatile var sustain = 0.7f
  @Volatile var releaseMs = 400f

  private var stage = Stage.IDLE
  private var level = 0f
  /** Level the release started from, so a short note still fades smoothly. */
  private var releaseFrom = 0f

  /** Note on. Restarts the attack from the current level, so retriggering
   *  while a note is still sounding does not click. */
  fun gateOn() {
    stage = Stage.ATTACK
  }

  /** Note off. */
  fun gateOff() {
    if (stage != Stage.IDLE) {
      releaseFrom = level
      stage = Stage.RELEASE
    }
  }

  val isIdle: Boolean get() = stage == Stage.IDLE && level <= 0f

  private fun stepFor(ms: Float): Float {
    val frames = (ms / 1000f) * sampleRate
    return if (frames <= 1f) 1f else 1f / frames
  }

  /** Next envelope value, 0..1. Call once per frame. */
  fun next(): Float {
    when (stage) {
      Stage.IDLE -> level = 0f
      Stage.ATTACK -> {
        level += stepFor(attackMs)
        if (level >= 1f) {
          level = 1f
          stage = Stage.DECAY
        }
      }
      Stage.DECAY -> {
        level -= stepFor(decayMs) * (1f - sustain)
        if (level <= sustain) {
          level = sustain
          stage = Stage.SUSTAIN
        }
      }
      Stage.SUSTAIN -> level = sustain
      Stage.RELEASE -> {
        // Exponential decay towards zero, with a floor so it actually ends.
        level -= stepFor(releaseMs) * releaseFrom
        if (level <= 0.0001f) {
          level = 0f
          stage = Stage.IDLE
        }
      }
    }
    return level
  }

  fun setParameter(key: String, value: Float) {
    when (key) {
      "attack" -> attackMs = value.coerceAtLeast(0.1f)
      "decay" -> decayMs = value.coerceAtLeast(0.1f)
      "sustain" -> sustain = value.coerceIn(0f, 1f)
      "release" -> releaseMs = value.coerceAtLeast(0.1f)
    }
  }
}

internal abstract class Generator(
  @Volatile var frequency: Float,
  @Volatile var amplitude: Float,
  protected val sampleRate: Int,
  protected val channelCount: Int,
) : AudioStreamCallback {

  @Volatile var isRunning: Boolean = false

  /**
   * Amplitude envelope.
   *
   * Bypassed until the first gate: a generator played with the transport
   * button should just sound, without needing a note event first.
   */
  val envelope = Envelope(sampleRate)
  @Volatile private var envelopeEngaged = false

  fun gate(on: Boolean) {
    envelopeEngaged = true
    if (on) envelope.gateOn() else envelope.gateOff()
  }

  /** Most recent peak, for metering without a separate tap. */
  private val lastPeakBits = AtomicInteger(0)

  var lastPeak: Float
    get() = Float.fromBits(lastPeakBits.get())
    private set(value) = lastPeakBits.set(value.toRawBits())

  /** One sample of the waveform at the current phase. */
  protected abstract fun nextSample(): Float

  final override fun onAudioReady(buffer: FloatArray, numFrames: Int): Int {
    if (!isRunning) {
      java.util.Arrays.fill(buffer, 0, numFrames * channelCount, 0f)
      lastPeak = 0f
      return numFrames
    }

    var peak = 0f
    var index = 0
    val gain = amplitude
    val gated = envelopeEngaged
    for (frame in 0 until numFrames) {
      val shaped = if (gated) envelope.next() else 1f
      val sample = nextSample() * gain * shaped
      val magnitude = abs(sample)
      if (magnitude > peak) peak = magnitude
      // Same sample to every channel: these sources are mono by nature.
      for (channel in 0 until channelCount) {
        buffer[index++] = sample
      }
    }
    lastPeak = peak
    return numFrames
  }
}

/** Phase-accumulating base for the pitched waveforms. */
internal abstract class PhaseGenerator(
  frequency: Float,
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
) : Generator(frequency, amplitude, sampleRate, channelCount) {

  /** Normalised phase, 0..1. */
  protected var phase = 0.0

  /** Phase advance per sample, 0..1. */
  protected val phaseIncrement: Double
    get() = frequency.toDouble() / sampleRate

  protected fun advance() {
    phase += phaseIncrement
    if (phase >= 1.0) phase -= 1.0
  }

  /**
   * PolyBLEP correction at a discontinuity.
   *
   * `t` is the normalised phase and `dt` the phase increment. Within one
   * increment either side of the step, a quadratic replaces the hard edge;
   * elsewhere the correction is zero.
   */
  protected fun polyBlep(t: Double, dt: Double): Double {
    if (dt <= 0.0) return 0.0
    return when {
      t < dt -> {
        val x = t / dt
        x + x - x * x - 1.0
      }
      t > 1.0 - dt -> {
        val x = (t - 1.0) / dt
        x * x + x + x + 1.0
      }
      else -> 0.0
    }
  }
}

internal class SineGenerator(
  frequency: Float,
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
) : PhaseGenerator(frequency, amplitude, sampleRate, channelCount) {
  // A sine has a single partial, so there is nothing to band limit.
  override fun nextSample(): Float {
    val value = sin(2.0 * PI * phase)
    advance()
    return value.toFloat()
  }
}

internal class SawGenerator(
  frequency: Float,
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
  private val antialias: Boolean,
) : PhaseGenerator(frequency, amplitude, sampleRate, channelCount) {

  override fun nextSample(): Float {
    val dt = phaseIncrement
    var value = 2.0 * phase - 1.0
    if (antialias) {
      value -= polyBlep(phase, dt)
    }
    advance()
    return value.toFloat()
  }
}

internal class SquareGenerator(
  frequency: Float,
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
  private val antialias: Boolean,
) : PhaseGenerator(frequency, amplitude, sampleRate, channelCount) {

  override fun nextSample(): Float {
    val dt = phaseIncrement
    var value = if (phase < 0.5) 1.0 else -1.0
    if (antialias) {
      // A square has two discontinuities per cycle: one at the wrap and one
      // at the half-way point, so it needs two corrections.
      value += polyBlep(phase, dt)
      value -= polyBlep((phase + 0.5) % 1.0, dt)
    }
    advance()
    return value.toFloat()
  }
}

internal class TriangleGenerator(
  frequency: Float,
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
) : PhaseGenerator(frequency, amplitude, sampleRate, channelCount) {

  override fun nextSample(): Float {
    // 1/n² harmonic rolloff makes naive generation inaudibly clean here.
    val value = 4.0 * abs(phase - 0.5) - 1.0
    advance()
    return value.toFloat()
  }
}

internal class WhiteNoiseGenerator(
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
) : Generator(0f, amplitude, sampleRate, channelCount) {
  private val random = Random(System.nanoTime())
  override fun nextSample(): Float = random.nextFloat() * 2f - 1f
}

/**
 * Pink noise: -3 dB per octave, equal energy per octave.
 *
 * Voss-McCartney with a fixed set of one-pole filters — the standard cheap
 * approximation, accurate to within a fraction of a decibel across the
 * audible band and a handful of multiplies per sample.
 */
internal class PinkNoiseGenerator(
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
) : Generator(0f, amplitude, sampleRate, channelCount) {
  private val random = Random(System.nanoTime())
  private var b0 = 0f
  private var b1 = 0f
  private var b2 = 0f
  private var b3 = 0f
  private var b4 = 0f
  private var b5 = 0f
  private var b6 = 0f

  override fun nextSample(): Float {
    val white = random.nextFloat() * 2f - 1f
    b0 = 0.99886f * b0 + white * 0.0555179f
    b1 = 0.99332f * b1 + white * 0.0750759f
    b2 = 0.96900f * b2 + white * 0.1538520f
    b3 = 0.86650f * b3 + white * 0.3104856f
    b4 = 0.55000f * b4 + white * 0.5329522f
    b5 = -0.7616f * b5 - white * 0.0168980f
    val pink = b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362f
    b6 = white * 0.115926f
    // The summed filters overshoot unity, so scale back into range.
    return (pink * 0.11f).coerceIn(-1f, 1f)
  }
}

/** Brown noise: -6 dB per octave, a leaky integration of white. */
internal class BrownNoiseGenerator(
  amplitude: Float,
  sampleRate: Int,
  channelCount: Int,
) : Generator(0f, amplitude, sampleRate, channelCount) {
  private val random = Random(System.nanoTime())
  private var last = 0f

  override fun nextSample(): Float {
    val white = random.nextFloat() * 2f - 1f
    // The leak keeps the random walk from drifting off as DC.
    last = ((last + 0.02f * white) / 1.02f).coerceIn(-1f, 1f)
    return last * 3.5f
  }
}

internal object GeneratorFactory {
  val waveforms = listOf(
    "sine", "square", "sawtooth", "triangle",
    "whiteNoise", "pinkNoise", "brownNoise",
  )

  fun isSupported(waveform: String) = waveform in waveforms

  fun create(
    waveform: String,
    frequency: Float,
    amplitude: Float,
    antialias: Boolean,
    sampleRate: Int,
    channelCount: Int,
  ): Generator? = when (waveform) {
    "sine" -> SineGenerator(frequency, amplitude, sampleRate, channelCount)
    "square" -> SquareGenerator(frequency, amplitude, sampleRate, channelCount, antialias)
    "sawtooth" -> SawGenerator(frequency, amplitude, sampleRate, channelCount, antialias)
    "triangle" -> TriangleGenerator(frequency, amplitude, sampleRate, channelCount)
    "whiteNoise" -> WhiteNoiseGenerator(amplitude, sampleRate, channelCount)
    "pinkNoise" -> PinkNoiseGenerator(amplitude, sampleRate, channelCount)
    "brownNoise" -> BrownNoiseGenerator(amplitude, sampleRate, channelCount)
    else -> null
  }
}
